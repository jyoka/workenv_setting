#!/bin/bash
# Export every Omarchy theme's colors so non-Omarchy machines (the Macs) can use them.
# Run on an Omarchy machine from the repo root: scripts/export_omarchy_themes.sh
#
# Writes, per theme:
#   config/ghostty/themes/<name>   Ghostty theme (colors only; font and size stay per machine)
#   config/nvim/themes/<name>.lua  lazy.nvim spec for the theme's Neovim colorscheme
#
# Rendering goes through Omarchy's own omarchy-theme-set-templates with a throwaway HOME,
# so the files match what `omarchy theme set <name>` generates.
set -euo pipefail

OMARCHY_PATH="${OMARCHY_PATH:-/usr/share/omarchy}"
REPO="$(cd "$(dirname "$0")/.." && pwd)"
GHOSTTY_OUT="$REPO/config/ghostty/themes"
NVIM_OUT="$REPO/config/nvim/themes"
mkdir -p "$GHOSTTY_OUT" "$NVIM_OUT"

work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

shopt -s nullglob
for theme_dir in "$OMARCHY_PATH"/themes/*/ "$HOME"/.config/omarchy/themes/*/; do
  name="$(basename "$theme_dir")"
  next="$work/$name/.local/state/omarchy/current/next-theme"
  mkdir -p "$next"
  # Theme-specific files win over templates, as in omarchy-theme-set
  cp "$theme_dir"/*.conf "$theme_dir"/*.lua "$theme_dir"/*.toml "$next"/ 2>/dev/null || true
  HOME="$work/$name" OMARCHY_PATH="$OMARCHY_PATH" PATH="$OMARCHY_PATH/bin:$PATH" \
    bash "$OMARCHY_PATH/bin/omarchy-theme-set-templates"

  if [[ -f $next/ghostty.conf ]]; then
    {
      echo "# Omarchy theme: $name (generated by scripts/export_omarchy_themes.sh)"
      echo "# Colors only: font and size stay in each machine's own config."
      cat "$next/ghostty.conf"
    } >"$GHOSTTY_OUT/$name"
  fi
  if [[ -f $next/neovim.lua ]]; then
    {
      echo "-- Omarchy theme: $name (generated by scripts/export_omarchy_themes.sh)"
      cat "$next/neovim.lua"
    } >"$NVIM_OUT/$name.lua"
  fi
  echo "$name"
done
